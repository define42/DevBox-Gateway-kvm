//go:build amd64

#include "textflag.h"

// Reconstruct two horizontally adjacent 4x4 blocks per kernel call. The
// horizontal transform retains int16 wrapping; AVX2 widens all eight columns
// before the vertical transform, preserving the scalar's full int16 domain.
TEXT ·idctFourT4RecAVX2(SB), NOSPLIT, $0-88
	MOVQ rec_base+0(FP), R9
	MOVQ recStride+24(FP), CX
	MOVQ pred_base+32(FP), R10
	MOVQ predStride+56(FP), SI
	MOVQ coeff_base+64(FP), R8
	MOVQ R9, BX
	MOVQ R10, DX
	MOVQ R8, AX
	CALL idctTwoT4RecAVX2Kernel<>(SB)
	LEAQ (R9)(CX*4), BX
	LEAQ (R10)(SI*4), DX
	LEAQ 64(R8), AX
	CALL idctTwoT4RecAVX2Kernel<>(SB)
	RET

// AX coefficients, BX output, CX output stride, DX prediction, SI prediction
// stride. R8-R10 survive. Each XMM contains one row from each independent block.
TEXT idctTwoT4RecAVX2Kernel<>(SB), NOSPLIT|NOFRAME, $0-0
	MOVQ 0(AX), X0
	MOVQ 32(AX), X4
	PUNPCKLQDQ X4, X0
	MOVQ 8(AX), X1
	MOVQ 40(AX), X4
	PUNPCKLQDQ X4, X1
	MOVQ 16(AX), X2
	MOVQ 48(AX), X4
	PUNPCKLQDQ X4, X2
	MOVQ 24(AX), X3
	MOVQ 56(AX), X4
	PUNPCKLQDQ X4, X3
	// Transpose each 4x4 matrix so packed word arithmetic runs horizontally.
	MOVOU X0, X4
	PUNPCKLWL X1, X4
	MOVOU X0, X6
	PUNPCKHWL X1, X6
	MOVOU X2, X5
	PUNPCKLWL X3, X5
	MOVOU X2, X7
	PUNPCKHWL X3, X7
	MOVOU X4, X8
	PUNPCKLLQ X5, X8
	PUNPCKHLQ X5, X4
	MOVOU X6, X9
	PUNPCKLLQ X7, X9
	PUNPCKHLQ X7, X6
	MOVOU X8, X0
	PUNPCKLQDQ X9, X0
	MOVOU X8, X1
	PUNPCKHQDQ X9, X1
	MOVOU X4, X2
	PUNPCKLQDQ X6, X2
	MOVOU X4, X3
	PUNPCKHQDQ X6, X3
	MOVOU X0, X4
	PADDW X2, X4
	PSUBW X2, X0
	MOVOU X3, X5
	PSRAW $1, X5
	PADDW X1, X5
	PSRAW $1, X1
	PSUBW X3, X1
	MOVOU X0, X2
	PSUBW X1, X2
	PADDW X0, X1
	MOVOU X4, X3
	PSUBW X5, X3
	MOVOU X4, X0
	PADDW X5, X0
	// Restore rows, then sign-extend every horizontal result to a dword.
	MOVOU X0, X4
	PUNPCKLWL X1, X4
	MOVOU X0, X6
	PUNPCKHWL X1, X6
	MOVOU X2, X5
	PUNPCKLWL X3, X5
	MOVOU X2, X7
	PUNPCKHWL X3, X7
	MOVOU X4, X8
	PUNPCKLLQ X5, X8
	PUNPCKHLQ X5, X4
	MOVOU X6, X9
	PUNPCKLLQ X7, X9
	PUNPCKHLQ X7, X6
	MOVOU X8, X0
	PUNPCKLQDQ X9, X0
	MOVOU X8, X1
	PUNPCKHQDQ X9, X1
	MOVOU X4, X2
	PUNPCKLQDQ X6, X2
	MOVOU X4, X3
	PUNPCKHQDQ X6, X3
	VPMOVSXWD X0, Y0
	VPMOVSXWD X1, Y1
	VPMOVSXWD X2, Y2
	VPMOVSXWD X3, Y3
	VPADDD Y2, Y0, Y4
	VPSUBD Y2, Y0, Y0
	VPSRAD $1, Y3, Y5
	VPADDD Y1, Y5, Y5
	VPSRAD $1, Y1, Y1
	VPSUBD Y3, Y1, Y1
	VPSUBD Y1, Y0, Y2
	VPADDD Y0, Y1, Y1
	VPSUBD Y5, Y4, Y3
	VPADDD Y5, Y4, Y0
	MOVL $32, R11
	VMOVD R11, X7
	VPBROADCASTD X7, Y7
	VPADDD Y7, Y0, Y0
	VPSRAD $6, Y0, Y0
	VPMOVZXBD (DX), Y4
	VPADDD Y4, Y0, Y0
	VEXTRACTI128 $1, Y0, X4
	VPACKSSDW X4, X0, X0
	VPACKUSWB X0, X0, X0
	VMOVQ X0, (BX)
	ADDQ CX, BX
	ADDQ SI, DX
	VPADDD Y7, Y1, Y1
	VPSRAD $6, Y1, Y1
	VPMOVZXBD (DX), Y4
	VPADDD Y4, Y1, Y1
	VEXTRACTI128 $1, Y1, X4
	VPACKSSDW X4, X1, X1
	VPACKUSWB X1, X1, X1
	VMOVQ X1, (BX)
	ADDQ CX, BX
	ADDQ SI, DX
	VPADDD Y7, Y2, Y2
	VPSRAD $6, Y2, Y2
	VPMOVZXBD (DX), Y4
	VPADDD Y4, Y2, Y2
	VEXTRACTI128 $1, Y2, X4
	VPACKSSDW X4, X2, X2
	VPACKUSWB X2, X2, X2
	VMOVQ X2, (BX)
	ADDQ CX, BX
	ADDQ SI, DX
	VPADDD Y7, Y3, Y3
	VPSRAD $6, Y3, Y3
	VPMOVZXBD (DX), Y4
	VPADDD Y4, Y3, Y3
	VEXTRACTI128 $1, Y3, X4
	VPACKSSDW X4, X3, X3
	VPACKUSWB X3, X3, X3
	VMOVQ X3, (BX)
	VZEROUPPER
	RET
